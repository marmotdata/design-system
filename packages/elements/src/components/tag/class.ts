import { LitElement, css, html, nothing, type PropertyValues } from 'lit';
import { property, query } from 'lit/decorators.js';
import { base } from '../../core/styles.js';
import { emit } from '../../core/events.js';
import { t } from '../../core/strings.js';
import '@marmotdata/icons/define.js';

export type TagVariant = 'plain' | 'pii' | 'certified' | 'generated' | 'plugin';

const s = (key: string, fallback: string): string => (t(key as never) as string | undefined) ?? fallback;

const VARIANTS: Record<TagVariant, { icon?: string; word?: () => string }> = {
  plain: {},
  pii: { icon: 'lock', word: () => s('tagPii', 'PII') },
  certified: { icon: 'verified', word: () => s('tagCertified', 'Certified') },
  generated: { word: () => s('tagGenerated', 'Generated') },
  plugin: { word: () => s('tagPlugin', 'Plugin') },
};

/**
 * Tags label an asset with a domain, classification or origin. They are plain by default: a
 * compact chip on `mm-sunken` in `mm-text-2`. Colour appears only when the tag means something:
 * `pii` (crimson, with a lock) and `certified` (moss, with a verified mark). `generated` and
 * `plugin` mark content generated by a plugin or an agent as a small outlined sentence-case caption
 * ("Generated"), with no sparkle.
 *
 * Long tags truncate with an ellipsis; the full text stays in the accessibility tree and is offered
 * as a native `title` only when it is actually cut off. With `removable`, the tag gets a remove
 * button named "Remove <tag>" that fires `mm-remove` on click, Enter, Space, Delete or Backspace;
 * the tag does not remove itself, so move focus to a sensible neighbour when you remove it. With
 * `href`, the tag text is a link.
 *
 * @tagname mm-tag
 * @summary Domain, classification or origin label.
 * @slot - The tag text. Defaults to the variant word for `pii`, `certified`, `generated` and `plugin`.
 * @csspart tag - The chip.
 * @csspart label - The text, or the link when `href` is set.
 * @csspart icon - The variant icon.
 * @csspart remove - The remove button.
 * @cssprop --mm-tag-max-width - Width at which the text truncates. Defaults to 24ch.
 * @fires mm-remove - {{ value: string }} The remove button was activated. Cancelable; the tag never removes itself.
 */
export class MmTag extends LitElement {
  static override styles = [
    base,
    css`
      :host {
        display: inline-flex;
        vertical-align: middle;
        max-inline-size: 100%;
      }
      .tag {
        display: inline-flex;
        align-items: center;
        gap: var(--space-1);
        block-size: 22px;
        max-inline-size: 100%;
        padding-inline: 7px;
        border-radius: var(--radius-sm);
        background: var(--mm-sunken);
        color: var(--mm-text-2);
        font: var(--text-caption);
        line-height: 1;
        white-space: nowrap;
      }
      .pii {
        background: var(--mm-danger-soft);
        color: var(--mm-danger);
        font-weight: 600;
      }
      .certified {
        background: var(--mm-success-soft);
        color: var(--mm-success);
        font-weight: 600;
      }
      .generated,
      .plugin {
        block-size: 18px;
        padding-inline: 5px;
        background: transparent;
        border: 1px solid var(--mm-rule);
        font: var(--text-caption);
        line-height: 1;
      }
      mm-icon {
        flex: none;
      }
      .label {
        display: block;
        min-inline-size: 0;
        max-inline-size: var(--mm-tag-max-width, 24ch);
        overflow: hidden;
        text-overflow: ellipsis;
        line-height: 22px;
        color: inherit;
        text-decoration: none;
        border-radius: 2px;
      }
      .generated .label,
      .plugin .label {
        line-height: 16px;
      }
      a.label:hover,
      a.label:focus-visible {
        color: var(--mm-text);
        text-decoration: underline;
        text-underline-offset: 2px;
      }
      a.label:focus-visible {
        outline-offset: 1px;
      }
      .remove {
        position: relative;
        display: inline-grid;
        place-items: center;
        flex: none;
        inline-size: 18px;
        block-size: 18px;
        margin-inline: -2px -4px;
        padding: 0;
        border: 0;
        border-radius: var(--radius-sm);
        background: transparent;
        color: inherit;
        cursor: pointer;
        transition: background-color var(--mm-dur-press) var(--mm-ease), color var(--mm-dur-press) var(--mm-ease);
      }
      /* Extends the hit area to 24px without growing the chip. */
      .remove::after {
        content: '';
        position: absolute;
        inset: -3px;
      }
      .remove:hover {
        color: var(--mm-text);
        background: color-mix(in oklab, currentColor 12%, transparent);
      }
      .remove:focus-visible {
        outline-offset: 0;
      }
    `,
  ];

  /** `plain` (default), `pii`, `certified`, `generated` or `plugin`. */
  @property({ reflect: true }) accessor variant: TagVariant = 'plain';
  /** Shows a remove button that fires `mm-remove`. */
  @property({ type: Boolean, reflect: true }) accessor removable = false;
  /** Makes the tag text a link, e.g. to the tag's Discover facet. */
  @property() accessor href = '';

  @query('.label') accessor #label!: HTMLElement | null;
  #ro?: ResizeObserver;
  #hasText = false;

  get text(): string {
    return this.textContent?.trim() || VARIANTS[this.variant]?.word?.() || '';
  }

  override connectedCallback(): void {
    super.connectedCallback();
    if (typeof ResizeObserver !== 'undefined') {
      this.#ro = new ResizeObserver(() => this.#syncTitle());
      this.#ro.observe(this);
    }
  }
  override disconnectedCallback(): void {
    super.disconnectedCallback();
    this.#ro?.disconnect();
  }

  protected override willUpdate(changed: PropertyValues<this>): void {
    super.willUpdate(changed);
    this.#hasText = !!this.textContent?.trim();
  }
  protected override updated(changed: PropertyValues<this>): void {
    super.updated(changed);
    this.#syncTitle();
  }

  /** Native title only when the text is cut off, so sighted mouse users can still read it. */
  #syncTitle() {
    const el = this.#label;
    if (!el) return;
    if (el.scrollWidth > el.clientWidth + 1) el.title = this.text;
    else el.removeAttribute('title');
  }

  #remove = () => {
    emit(this, 'mm-remove', { value: this.text }, { cancelable: true });
  };

  #onRemoveKey = (e: KeyboardEvent) => {
    if (e.key === 'Delete' || e.key === 'Backspace') {
      e.preventDefault();
      this.#remove();
    }
  };

  override render() {
    const v = VARIANTS[this.variant] ?? VARIANTS.plain;
    const content = html`<slot @slotchange=${() => this.requestUpdate()}></slot>${this.#hasText ? nothing : (v.word?.() ?? '')}`;
    return html`<span part="tag" class="tag ${this.variant}">
      ${v.icon ? html`<mm-icon part="icon" name=${v.icon} size="14"></mm-icon>` : nothing}
      ${this.href
        ? html`<a part="label" class="label" href=${this.href}>${content}</a>`
        : html`<span part="label" class="label">${content}</span>`}
      ${this.removable
        ? html`<button
            part="remove"
            class="remove"
            type="button"
            aria-label="${t('remove')} ${this.text}"
            @click=${this.#remove}
            @keydown=${this.#onRemoveKey}
          >
            <mm-icon name="close" size="14"></mm-icon>
          </button>`
        : nothing}
    </span>`;
  }
}

declare global {
  interface HTMLElementTagNameMap {
    'mm-tag': MmTag;
  }
}
