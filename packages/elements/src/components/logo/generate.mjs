// Regenerates artwork.ts from the fixed Marmot wordmark in packages/tokens/source/logos.
// Run with `node packages/elements/src/components/logo/generate.mjs` whenever the design system
// supplies new artwork. Paths and fills are copied untouched: only the XML prolog and the
// illustrator ids (which would collide in one document) are removed.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = new URL('./', import.meta.url);
const logos = new URL('../../../../tokens/source/logos/', import.meta.url);

// The logo is the wordmark only (decided 2026-10-27): the marmot illustration is not used.
const files = {
  wordmark: 'marmot-wordmark.svg',
};

const clean = (svg) =>
  svg
    .replace(/<\?xml[^>]*\?>/, '')
    .replace(/\s(id)="[^"]*"/g, '')
    .replace(/\r?\n\s*/g, '')
    .trim();

const viewBox = (svg) => {
  const m = /viewBox="([^"]+)"/.exec(svg);
  if (!m) throw new Error('Artwork has no viewBox');
  const [, , w, h] = m[1].split(/\s+/).map(Number);
  return { width: w, height: h };
};

let out = `// Generated by generate.mjs from packages/tokens/source/logos. Do not edit by hand.\n\n`;
for (const [name, file] of Object.entries(files)) {
  const svg = clean(readFileSync(new URL(file, logos), 'utf8'));
  const { width, height } = viewBox(svg);
  out += `/** ${file} (${width} × ${height}). */\n`;
  out += `export const ${name} = { svg: ${JSON.stringify(svg)}, width: ${width}, height: ${height} } as const;\n\n`;
}
writeFileSync(new URL('artwork.ts', here), out);
console.log(`Wrote ${fileURLToPath(new URL('artwork.ts', here))}`);
