// Generates src/index.ts from the component folders, so adding a component never needs a hand edit.
import { readdirSync, existsSync, writeFileSync } from 'node:fs';
const dir = new URL('../src/components/', import.meta.url);
// Only folders with both files; run at build and checkpoint time, never while components are mid-flight.
const names = readdirSync(dir).filter((n) => existsSync(new URL(`${n}/define.ts`, dir)) && existsSync(new URL(`${n}/class.ts`, dir))).sort();
writeFileSync(
  new URL('../src/index.ts', import.meta.url),
  `/* Generated by scripts/gen-index.mjs. Do not edit. */\nexport * from './core/index.js';\n${names.map((n) => `export * from './components/${n}/define.js';`).join('\n')}\n`,
);
console.log(`index: ${names.length} components`);
