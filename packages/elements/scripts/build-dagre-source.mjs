// Bundles dagre as an IIFE string so the lineage layout worker can run it with no app setup.
// The generated module is imported lazily, only for graphs large enough to need the worker.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
const out = await build({
  stdin: { contents: "export { default } from '@dagrejs/dagre';", resolveDir: new URL('..', import.meta.url).pathname },
  bundle: true, minify: true, write: false, format: 'iife', globalName: '__mmDagre', platform: 'browser', logLevel: 'silent',
});
const code = out.outputFiles[0].text;
writeFileSync(
  new URL('../src/components/lineage-canvas/dagre-source.generated.ts', import.meta.url),
  `/* Generated by scripts/build-dagre-source.mjs from @dagrejs/dagre. Do not edit. */\nconst source: string = ${JSON.stringify(code)};\nexport default source;\n`,
);
console.log(`dagre worker source: ${(code.length / 1024).toFixed(0)} KB`);
