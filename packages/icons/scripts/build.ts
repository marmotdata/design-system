/**
 * Builds the offline icon data for @marmotdata/icons. Icons are never fetched at runtime:
 * self-hosted Marmot can run without internet access.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as simpleIcons from 'simple-icons';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
type IconSet = { prefix: string; width?: number; height?: number; icons: Record<string, { body: string; width?: number; height?: number }>; aliases?: Record<string, { parent: string }> };
const sets: Record<string, IconSet> = {
  'material-symbols': require('@iconify-json/material-symbols/icons.json'),
  logos: require('@iconify-json/logos/icons.json'),
  devicon: require('@iconify-json/devicon/icons.json'),
  'simple-icons': require('@iconify-json/simple-icons/icons.json'),
};

export interface IconData { body: string; width: number; height: number }

function resolve(ref: string): IconData {
  const [prefix, name] = ref.split(':') as [string, string];
  const set = sets[prefix];
  if (!set) throw new Error(`Unknown icon set ${prefix}`);
  let key = name;
  if (!set.icons[key] && set.aliases?.[key]) key = set.aliases[key]!.parent;
  const icon = set.icons[key];
  if (!icon) throw new Error(`Icon ${ref} not found`);
  return { body: icon.body, width: icon.width ?? set.width ?? 16, height: icon.height ?? set.height ?? 16 };
}

// ---- UI icons ----
const names = readFileSync(join(here, '../src/ui-icons.txt'), 'utf8')
  .split('\n').filter((l) => !l.startsWith('#')).join(' ').split(/\s+/).filter(Boolean);
const ms = sets['material-symbols']!;
const ui: Record<string, IconData> = {};
for (const n of new Set(names)) {
  const outline = `${n}-outline`;
  ui[n] = resolve(`material-symbols:${ms.icons[outline] ? outline : n}`);
}

// ---- Provider marks ----
type ProviderEntry = { name: string; icon: string; dark?: string; color?: 'ink'; generic?: boolean };
const providers: Record<string, ProviderEntry> = JSON.parse(readFileSync(join(here, '../src/providers.data.json'), 'utf8'));
const siBySlug = new Map(Object.values(simpleIcons as Record<string, { slug: string; hex: string }>).filter((v) => v && v.slug).map((v) => [v.slug, v.hex]));
const luminance = (hex: string) => {
  const c = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((x) => (x <= 0.04045 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0]! + 0.7152 * c[1]! + 0.0722 * c[2]!;
};
/** Marks whose artwork is (near) black are drawn in ink so they read on Peat without being recoloured. */
const isBlackArtwork = (body: string) => {
  const fills = [...body.matchAll(/fill="(#[0-9a-fA-F]{3,6})"/g)].map((m) => m[1]!.replace(/^#(.)(.)(.)$/, '#$1$1$2$2$3$3'));
  return fills.length > 0 && fills.every((f) => luminance(f.slice(1)) < 0.02);
};
const out: Record<string, { name: string; light: IconData; dark?: IconData; tone: 'artwork' | 'ink' | 'brand'; brand?: string; generic?: boolean }> = {};
for (const [key, p] of Object.entries(providers)) {
  const light = resolve(p.icon);
  const prefix = p.icon.split(':')[0];
  let tone: 'artwork' | 'ink' | 'brand' = 'artwork';
  let brand: string | undefined;
  if (p.generic || p.color === 'ink') tone = 'ink';
  else if (prefix === 'simple-icons') {
    const hex = siBySlug.get(p.icon.split(':')[1]!);
    if (!hex || luminance(hex) < 0.02) tone = 'ink';
    else { tone = 'brand'; brand = `#${hex}`; }
  } else if (isBlackArtwork(light.body)) {
    // Black artwork becomes ink: the same mark, drawn in mm-text so it reads on Peat (guidelines: use the dark variant, never tint).
    tone = 'ink';
    light.body = light.body.replace(/fill="#[0-9a-fA-F]{3,6}"/g, 'fill="currentColor"');
  }
  out[key] = { name: p.name, light, ...(p.dark ? { dark: resolve(p.dark) } : {}), tone, ...(brand ? { brand } : {}), ...(p.generic ? { generic: true } : {}) };
}

const gen = join(here, '../src/generated');
mkdirSync(gen, { recursive: true });
const header = '/* Generated by scripts/build.ts from @iconify-json data. Do not edit. */\n';
writeFileSync(join(gen, 'ui-icons.ts'), `${header}import type { IconData } from '../registry.js';\nexport const uiIcons: Record<string, IconData> = ${JSON.stringify(ui)};\nexport type UiIconName = ${Object.keys(ui).map((k) => JSON.stringify(k)).join(' | ')};\n`);
rmSync(join(gen, 'providers'), { recursive: true, force: true });
mkdirSync(join(gen, 'providers'), { recursive: true });
for (const [k, v] of Object.entries(out)) {
  writeFileSync(join(gen, 'providers', `${k}.ts`), `${header}import type { ProviderMark } from '../../registry.js';\nconst mark: ProviderMark = ${JSON.stringify(v)};\nexport default mark;\n`);
}
const ident = (k: string) => `p_${k.replace(/[^a-z0-9]/gi, '_')}`;
writeFileSync(join(gen, 'provider-loaders.ts'), `${header}import type { ProviderMark } from '../registry.js';\n/** Lazy loaders: bundlers split each mark into its own chunk, so pages only download the providers they show. */\nexport const providerLoaders: Record<string, () => Promise<{ default: ProviderMark }>> = {\n${Object.keys(out).map((k) => `  ${JSON.stringify(k)}: () => import('./providers/${k}.js'),`).join('\n')}\n};\nexport const providerNames: Record<string, string> = ${JSON.stringify(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.name])))};\nexport type ProviderName = ${Object.keys(out).map((k) => JSON.stringify(k)).join(' | ')};\n`);
writeFileSync(join(gen, 'providers-all.ts'), `${header}import type { ProviderMark } from '../registry.js';\n${Object.keys(out).map((k) => `import ${ident(k)} from './providers/${k}.js';`).join('\n')}\nexport const providerMarks: Record<string, ProviderMark> = {\n${Object.keys(out).map((k) => `  ${JSON.stringify(k)}: ${ident(k)},`).join('\n')}\n};\n`);
const peatPaper = '151210';
const ratio = (a: string, b: string) => { const [x, y] = [luminance(a), luminance(b)].sort((m, n) => n - m); return (x! + 0.05) / (y! + 0.05); };
const lowOnPeat = Object.entries(out).filter(([, v]) => {
  if (v.tone !== 'artwork' || v.dark) return false;
  const fills = [...v.light.body.matchAll(/fill="#([0-9a-fA-F]{6})"/g)].map((m) => m[1]!);
  return fills.length > 0 && fills.every((f) => ratio(f, peatPaper) < 2);
}).map(([k]) => k);
const missing = Object.entries(out).filter(([, v]) => v.generic).map(([k]) => k);
writeFileSync(join(here, '../MISSING-MARKS.md'), `# Providers without a bundled mark\n\nThese render a neutral Material Symbol in ink beside the provider name. The design system should supply artwork for them.\n\n${missing.map((m) => `- \`${m}\` (${out[m]!.name})`).join('\n')}\n\n## Marks that need a Peat variant\n\nEvery fill in these marks is below 2:1 on Peat paper (#151210). They are shown as supplied, never recoloured; the design system should supply dark-ground artwork.\n\n${lowOnPeat.map((m) => `- \`${m}\` (${out[m]!.name})`).join('\n') || '- None'}\n`);
console.log(`icons: ${Object.keys(ui).length} UI icons, ${Object.keys(out).length} providers (${missing.length} generic)`);
