/**
 * Bundle-size budget per element. Each public entry (`@marmotdata/elements/<name>.js`) is bundled
 * with esbuild, minified and gzipped, the way an app would ship it. Lit is included (an app pays for
 * it once, but an element must not hide a second copy); the icon registry data and provider marks
 * are excluded because apps load them once from @marmotdata/icons.
 *
 *   node measure.ts            check against budgets.json, exit 1 on any overrun
 *   node measure.ts --update   write current sizes + 10% headroom as the new budgets
 */
import { build } from 'esbuild';
import { gzipSync } from 'node:zlib';
import { readdirSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../packages/elements/dist/components/', import.meta.url));
const budgetsFile = fileURLToPath(new URL('./budgets.json', import.meta.url));
const update = process.argv.includes('--update');
const budgets: Record<string, number> = existsSync(budgetsFile) ? JSON.parse(readFileSync(budgetsFile, 'utf8')) : {};

const names = readdirSync(root).filter((n) => existsSync(`${root}${n}/define.js`)).sort();
const rows: { name: string; kb: number; lazy: number; budget?: number; ok: boolean }[] = [];
for (const name of names) {
  const out = await build({
    entryPoints: [`${root}${name}/define.js`],
    bundle: true,
    minify: true,
    write: false,
    // Split at dynamic imports so lazily loaded code (CodeMirror, the lineage layout) is not counted
    // as up-front cost. The budget is the initial load; lazy chunks are reported separately.
    splitting: true,
    outdir: '/virtual',
    metafile: true,
    format: 'esm',
    platform: 'browser',
    logLevel: 'silent',
    // Icon data and provider marks are shared assets, measured separately below.
    external: ['@marmotdata/icons/ui.js', '@marmotdata/icons/providers-all.js', './generated/providers/*'],
    plugins: [{
      name: 'icon-data',
      setup(b) {
        b.onResolve({ filter: /generated\/(ui-icons|providers-all|providers\/.*)\.js$/ }, (a) => ({ path: a.path, external: true }));
        b.onResolve({ filter: /^@marmotdata\/icons\/ui\.js$/ }, (a) => ({ path: a.path, external: true }));
        b.onResolve({ filter: /^@marmotdata\/icons\/define\.js$/ }, () => ({ path: fileURLToPath(new URL('../../packages/icons/dist/icon.js', import.meta.url)) }));
      },
    }],
  });
  const entryOut = Object.entries(out.metafile!.outputs).find(([, o]) => o.entryPoint)![0];
  const gz = (path: string) => gzipSync(out.outputFiles.find((f) => f.path.endsWith(path.replace(/^.*\//, '/')))!.contents).length / 1024;
  // Initial load = the entry plus every chunk it imports statically.
  const seen = new Set<string>();
  const walk = (p: string) => {
    if (seen.has(p)) return;
    seen.add(p);
    for (const i of out.metafile!.outputs[p]!.imports) if (i.kind === 'import-statement' && !i.external) walk(i.path);
  };
  walk(entryOut);
  const kb = [...seen].reduce((sum, p) => sum + gz(p), 0);
  const lazy = Object.keys(out.metafile!.outputs).filter((p) => !seen.has(p) && p.endsWith('.js')).reduce((sum, p) => sum + gz(p), 0);
  const budget = budgets[name];
  rows.push({ name, kb, lazy, budget, ok: budget === undefined || kb <= budget });
}

if (update) {
  writeFileSync(budgetsFile, JSON.stringify(Object.fromEntries(rows.map((r) => [r.name, Math.ceil(r.kb * 1.1 * 10) / 10])), null, 2) + '\n');
  console.log(`size: wrote ${rows.length} budgets`);
}
const report = `# Bundle sizes\n\nMinified and gzipped, per public entry, including Lit, excluding shared icon data. Initial is what loads with the element; lazy chunks (CodeMirror, the lineage layout) load on first use. Generated by \`tools/size/measure.ts\`.\n\n| Element entry | Initial (KB) | Lazy (KB) | Budget (KB) |\n|---|---:|---:|---:|\n${rows.map((r) => `| \`${r.name}.js\` | ${r.kb.toFixed(1)} | ${r.lazy ? r.lazy.toFixed(1) : ''} | ${r.budget?.toFixed(1) ?? 'none'} |`).join('\n')}\n`;
writeFileSync(fileURLToPath(new URL('./REPORT.md', import.meta.url)), report);
const over = rows.filter((r) => !r.ok);
console.log(`size: ${rows.length} entries, ${over.length} over budget`);
if (over.length && !update) {
  for (const r of over) console.error(`  ${r.name}: ${r.kb.toFixed(1)} KB > ${r.budget} KB`);
  process.exit(1);
}
