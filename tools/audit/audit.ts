/**
 * Static audit of every element folder against docs/authoring.md. Prints a table of gaps; with
 * --strict exits 1 on any. Checks what can be checked from source: the guidelines states a person still
 * reviews the screenshots.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../packages/elements/src/components', import.meta.url));
type Row = { name: string; gaps: string[] };
const rows: Row[] = [];

for (const name of readdirSync(root).sort()) {
  const dir = join(root, name);
  const classFile = join(dir, 'class.ts');
  if (!existsSync(classFile)) continue;
  const cls = readFileSync(classFile, 'utf8');
  const storyFile = join(dir, `${name}.stories.ts`);
  const stories = existsSync(storyFile) ? readFileSync(storyFile, 'utf8') : '';
  const gaps: string[] = [];
  if (!stories) gaps.push('no stories');
  else {
    const exported = [...stories.matchAll(/export const (\w+)/g)].map((m) => m[1]!);
    if (!/usage:\s*\{/.test(stories) && !/usage\s*=/.test(stories)) gaps.push('no usage tabs');
    if (!/react/.test(stories) || !/svelte/.test(stories)) gaps.push('usage missing React or Svelte');
    if (!exported.some((e) => /Rtl|RightToLeft/i.test(e)) && !/dir:\s*'rtl'/.test(stories)) gaps.push('no RTL story');
    if (!/themes\(/.test(stories)) gaps.push('no both-themes story');
    const interactive = /tabindex|<button|<input|<textarea|@keydown|delegatesFocus/.test(cls);
    if (interactive && !/play:/.test(stories)) gaps.push('interactive but no play test');
    if (interactive && !/press\(|tab\(/.test(stories)) gaps.push('no keyboard test');
  }
  for (const m of cls.matchAll(/@fires (mm-[\w-]+)(?![\w-])(?! - \{)/g)) gaps.push(`@fires ${m[1]} has no detail type`);
  for (const m of cls.matchAll(/override (willUpdate|updated|firstUpdated|update)\(\)/g)) gaps.push(`${m[1]}() drops changedProperties (breaks subclasses)`);
  const styles = [...cls.matchAll(/css`([\s\S]*?)`/g), ...cls.matchAll(/style(?:Map)?=\$?\{?[`'"]([^`'"]*)[`'"]/g)].map((m) => m[1]!).join('\n');
  for (const m of styles.matchAll(/\b(margin|padding|border)-(left|right)\b|(?<![\w-])(left|right):\s*[^;]*;|text-align:\s*(left|right)/g)) gaps.push(`physical property "${m[0].slice(0, 30)}" (use logical)`);
  if (/transition:\s*all/.test(cls)) gaps.push('transition: all');
  if (/#[0-9a-fA-F]{3,8}\b|rgba?\(/.test(cls.replace(/\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, ''))) gaps.push('raw colour');
  rows.push({ name, gaps: [...new Set(gaps)] });
}

const withGaps = rows.filter((r) => r.gaps.length);
const report = `# Component audit\n\nGenerated by \`tools/audit/audit.ts\` from source. ${rows.length} element folders, ${withGaps.length} with gaps.\n\n| Element | Gaps |\n|---|---|\n${withGaps.map((r) => `| \`${r.name}\` | ${r.gaps.join('; ')} |`).join('\n')}\n`;
writeFileSync(fileURLToPath(new URL('./REPORT.md', import.meta.url)), report);
console.log(`audit: ${rows.length} folders, ${withGaps.length} with gaps`);
if (process.argv.includes('--strict') && withGaps.length) process.exit(1);
