/** Checks every documented pair in both themes against WCAG 2.2. Exits 1 on any unallowed failure. */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { contrast, threshold } from './lib.ts';
import { pairs } from './pairs.ts';

const tokens = JSON.parse(readFileSync(fileURLToPath(new URL('../../packages/tokens/source/tokens.json', import.meta.url)), 'utf8'));
const colors: Record<string, { light: string; dark: string }> = Object.fromEntries(
  tokens.color.tokens.map((t: { name: string; value: { light: string; dark: string } }) => [t.name, t.value]),
);

const rows: string[] = [];
let failures = 0;
let allowed = 0;
for (const p of pairs) {
  for (const theme of p.themes ?? (['light', 'dark'] as const)) {
    const fg = colors[p.fg]?.[theme];
    const bg = colors[p.bg]?.[theme];
    if (!fg || !bg) {
      console.error(`Unknown token in pair ${p.fg} on ${p.bg}`);
      failures++;
      continue;
    }
    const ratio = contrast(fg, bg);
    const pass = ratio >= threshold[p.kind];
    const status = pass ? 'pass' : p.allow ? 'allowed' : 'FAIL';
    if (status === 'FAIL') failures++;
    if (status === 'allowed') allowed++;
    rows.push(`| ${p.fg} | ${p.bg} | ${theme === 'dark' ? 'Peat' : 'Light'} | ${ratio.toFixed(2)} | ${threshold[p.kind]} | ${status} | ${p.where} |`);
  }
}

const report = `# Contrast report\n\nGenerated by \`tools/contrast/check.ts\` from \`packages/tokens/source/tokens.json\`.\n\n| Foreground | Background | Theme | Ratio | Needs | Result | Used for |\n|---|---|---|---|---|---|---|\n${rows.join('\n')}\n`;
writeFileSync(fileURLToPath(new URL('./REPORT.md', import.meta.url)), report);
console.log(`contrast: ${rows.length} checks, ${failures} failures, ${allowed} allowed exceptions`);
if (failures) {
  console.error(rows.filter((r) => r.includes('FAIL')).join('\n'));
  process.exit(1);
}
